-- 空库初始化。已有库由 apply_migrations 在检测到 questions 表后标记为已应用。
CREATE TABLE IF NOT EXISTS schema_migrations (
  id text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  display_name text NOT NULL DEFAULT '',
  avatar_url text,
  audience text NOT NULL DEFAULT 'unset',
  status text NOT NULL DEFAULT 'active',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT users_audience_check CHECK (audience = ANY (ARRAY['unset', 'transition', 'experienced'])),
  CONSTRAINT users_status_check CHECK (status = ANY (ARRAY['active', 'disabled']))
);

CREATE TABLE IF NOT EXISTS topics (
  id text PRIMARY KEY,
  bank text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  name text NOT NULL,
  english text NOT NULL DEFAULT '',
  summary text NOT NULL DEFAULT '',
  interviewer_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT topics_bank_check CHECK (bank = ANY (ARRAY['alibaba', 'ailian'])),
  CONSTRAINT topics_bank_sort_unique UNIQUE (bank, sort_order)
);

CREATE TABLE IF NOT EXISTS questions (
  id text PRIMARY KEY,
  parent_id text REFERENCES questions(id) ON DELETE CASCADE,
  prerequisite_id text REFERENCES questions(id) ON DELETE SET NULL,
  level smallint NOT NULL,
  topic_id text NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  difficulty text NOT NULL DEFAULT '基础',
  angle text NOT NULL DEFAULT '',
  title text NOT NULL,
  question text NOT NULL,
  gist text NOT NULL DEFAULT '',
  points jsonb NOT NULL DEFAULT '[]'::jsonb,
  bonus text NOT NULL DEFAULT '',
  red_flags text NOT NULL DEFAULT '',
  source jsonb,
  full_answer text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  status text NOT NULL DEFAULT 'published',
  content_version text NOT NULL DEFAULT '1.0.0',
  experience_level text,
  question_type text,
  CONSTRAINT questions_level_check CHECK (level = ANY (ARRAY[1, 2, 3])),
  CONSTRAINT questions_difficulty_check CHECK (difficulty = ANY (ARRAY['基础', '进阶', '场景', '深挖', '系统设计'])),
  CONSTRAINT questions_status_check CHECK (status = ANY (ARRAY['draft', 'published', 'retired'])),
  CONSTRAINT questions_experience_level_check CHECK (experience_level = ANY (ARRAY['入门', '进阶', '生产实战', '架构'])),
  CONSTRAINT questions_question_type_check CHECK (question_type = ANY (ARRAY['概念', '项目深挖', '故障复盘', '系统设计', '编码']))
);

CREATE TABLE IF NOT EXISTS question_labels (
  question_id text NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  kind text NOT NULL,
  value text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (question_id, kind, value),
  CONSTRAINT question_labels_kind_check CHECK (kind = ANY (ARRAY['audience', 'role', 'domain', 'capability']))
);

CREATE TABLE IF NOT EXISTS learning_paths (
  id text PRIMARY KEY,
  name text NOT NULL,
  summary text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS learning_path_items (
  path_id text NOT NULL REFERENCES learning_paths(id) ON DELETE CASCADE,
  topic_id text NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  sort_order integer NOT NULL,
  PRIMARY KEY (path_id, topic_id),
  CONSTRAINT learning_path_items_path_id_sort_order_key UNIQUE (path_id, sort_order)
);

CREATE TABLE IF NOT EXISTS app_meta (
  key text PRIMARY KEY,
  value jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS content_releases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version text NOT NULL UNIQUE,
  summary text NOT NULL DEFAULT '',
  published_at timestamptz NOT NULL DEFAULT now(),
  is_current boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS devices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES users(id) ON DELETE CASCADE,
  platform text NOT NULL,
  device_name text NOT NULL DEFAULT '',
  app_version text,
  push_token text,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT devices_platform_check CHECK (platform = ANY (ARRAY['harmony', 'web', 'android', 'ios']))
);

CREATE TABLE IF NOT EXISTS auth_identities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider text NOT NULL,
  provider_uid text NOT NULL,
  extra jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT auth_identities_provider_check CHECK (provider = ANY (ARRAY['huawei', 'phone', 'local'])),
  CONSTRAINT auth_identities_provider_provider_uid_key UNIQUE (provider, provider_uid)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  device_id uuid REFERENCES devices(id) ON DELETE SET NULL,
  refresh_token_hash text NOT NULL UNIQUE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);

CREATE TABLE IF NOT EXISTS membership_plans (
  id text PRIMARY KEY,
  name text NOT NULL,
  price_cents integer NOT NULL DEFAULT 0,
  period_days integer,
  huawei_product_id text,
  sort_order integer NOT NULL DEFAULT 0,
  CONSTRAINT membership_plans_price_cents_check CHECK (price_cents >= 0)
);

CREATE TABLE IF NOT EXISTS memberships (
  user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  plan_id text NOT NULL REFERENCES membership_plans(id),
  status text NOT NULL,
  starts_at timestamptz NOT NULL DEFAULT now(),
  ends_at timestamptz,
  auto_renew boolean NOT NULL DEFAULT false,
  source text NOT NULL DEFAULT 'none',
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT memberships_status_check CHECK (status = ANY (ARRAY['active', 'expired', 'cancelled', 'grace'])),
  CONSTRAINT memberships_source_check CHECK (source = ANY (ARRAY['none', 'huawei_iap', 'manual']))
);

CREATE TABLE IF NOT EXISTS iap_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plan_id text NOT NULL REFERENCES membership_plans(id),
  provider text NOT NULL DEFAULT 'huawei_iap',
  product_id text NOT NULL,
  purchase_token text NOT NULL UNIQUE,
  order_no text,
  status text NOT NULL,
  raw_payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT iap_orders_status_check CHECK (status = ANY (ARRAY['pending', 'paid', 'refunded', 'failed']))
);

CREATE TABLE IF NOT EXISTS user_profiles (
  user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  experience_years smallint,
  job_role text,
  target_role text,
  domains text[] NOT NULL DEFAULT '{}'::text[],
  bio text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_progress (
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id text NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  mastered boolean NOT NULL DEFAULT false,
  last_score numeric(5,2),
  attempt_count integer NOT NULL DEFAULT 0,
  last_practiced_at timestamptz,
  next_review_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, question_id)
);

CREATE TABLE IF NOT EXISTS resumes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  file_name text NOT NULL DEFAULT '',
  file_mime text,
  file_size_bytes integer,
  storage_key text,
  raw_text text,
  parse_status text NOT NULL DEFAULT 'uploaded',
  parse_error text,
  is_active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT resumes_parse_status_check CHECK (parse_status = ANY (ARRAY['uploaded', 'parsing', 'parsed', 'needs_review', 'failed']))
);

CREATE TABLE IF NOT EXISTS resume_profiles (
  resume_id uuid PRIMARY KEY REFERENCES resumes(id) ON DELETE CASCADE,
  full_name text NOT NULL DEFAULT '',
  years_experience smallint,
  current_title text,
  target_title text,
  summary text NOT NULL DEFAULT '',
  skills text[] NOT NULL DEFAULT '{}'::text[],
  confirmed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS resume_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  resume_id uuid NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  company text NOT NULL,
  job_title text NOT NULL DEFAULT '',
  started_on date,
  ended_on date,
  is_current boolean NOT NULL DEFAULT false,
  summary text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS resume_projects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  resume_id uuid NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  job_id uuid REFERENCES resume_jobs(id) ON DELETE SET NULL,
  name text NOT NULL,
  company text,
  job_role text,
  started_on date,
  ended_on date,
  is_current boolean NOT NULL DEFAULT false,
  tech_stack text[] NOT NULL DEFAULT '{}'::text[],
  responsibilities text NOT NULL DEFAULT '',
  outcomes text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS resume_questions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  resume_id uuid NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
  project_id uuid REFERENCES resume_projects(id) ON DELETE CASCADE,
  parent_id uuid REFERENCES resume_questions(id) ON DELETE CASCADE,
  level smallint NOT NULL,
  angle text NOT NULL DEFAULT '',
  question text NOT NULL,
  gist text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT resume_questions_level_check CHECK (level = ANY (ARRAY[1, 2, 3])),
  CONSTRAINT resume_questions_status_check CHECK (status = ANY (ARRAY['draft', 'ready', 'retired']))
);

CREATE TABLE IF NOT EXISTS practice_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id text REFERENCES questions(id) ON DELETE CASCADE,
  device_id uuid REFERENCES devices(id) ON DELETE SET NULL,
  input_mode text NOT NULL,
  answer_text text NOT NULL DEFAULT '',
  judge_mode text,
  score numeric(5,2),
  verdict text,
  judge_result jsonb,
  duration_ms integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  resume_question_id uuid REFERENCES resume_questions(id) ON DELETE CASCADE,
  CONSTRAINT practice_records_input_mode_check CHECK (input_mode = ANY (ARRAY['text', 'voice', 'listen'])),
  CONSTRAINT practice_records_judge_mode_check CHECK (judge_mode = ANY (ARRAY['offline', 'llm'])),
  CONSTRAINT practice_records_verdict_check CHECK (verdict = ANY (ARRAY['过', '追问', '挂'])),
  CONSTRAINT practice_records_question_source_check CHECK (num_nonnulls(question_id, resume_question_id) = 1)
);

CREATE TABLE IF NOT EXISTS mock_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  mode text NOT NULL,
  bank text NOT NULL DEFAULT 'all',
  status text NOT NULL DEFAULT 'active',
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  resume_id uuid REFERENCES resumes(id) ON DELETE SET NULL,
  resume_project_id uuid REFERENCES resume_projects(id) ON DELETE SET NULL,
  CONSTRAINT mock_sessions_mode_check CHECK (mode = ANY (ARRAY['transition', 'project_deep', 'architecture', 'mixed'])),
  CONSTRAINT mock_sessions_bank_check CHECK (bank = ANY (ARRAY['all', 'alibaba', 'ailian'])),
  CONSTRAINT mock_sessions_status_check CHECK (status = ANY (ARRAY['active', 'finished', 'abandoned']))
);

CREATE TABLE IF NOT EXISTS mock_session_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id uuid NOT NULL REFERENCES mock_sessions(id) ON DELETE CASCADE,
  question_id text REFERENCES questions(id) ON DELETE CASCADE,
  sort_order integer NOT NULL,
  practice_record_id uuid REFERENCES practice_records(id) ON DELETE SET NULL,
  resume_question_id uuid REFERENCES resume_questions(id) ON DELETE CASCADE,
  CONSTRAINT mock_session_items_session_id_sort_order_key UNIQUE (session_id, sort_order),
  CONSTRAINT mock_session_items_question_source_check CHECK (num_nonnulls(question_id, resume_question_id) = 1)
);

CREATE TABLE IF NOT EXISTS sync_states (
  device_id uuid PRIMARY KEY REFERENCES devices(id) ON DELETE CASCADE,
  content_release_id bigint REFERENCES content_releases(id),
  progress_synced_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

